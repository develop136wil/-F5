import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir} from 'node:fs/promises';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
test('공통 도우미: 단일 입력, 미저장 닫기, 이어하기, 저장 중 닫기 방지',async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try {
  const page=await browser.newPage({viewport:{width:850,height:650}});
  const errors=[]; page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',r=>{const u=new URL(r.request().url());return u.origin==='http://127.0.0.1:1420'&&!u.pathname.startsWith('/api/')?r.continue():r.abort();});
  await page.goto('http://127.0.0.1:1420/tests/ui/settings-drafts.html');
  assert.equal(await page.locator('input[type=password]').count(),0);
  await page.getByRole('link',{name:'Gemini 연결하기',exact:true}).click();
  const dialog=page.getByRole('dialog',{name:'연결·설정 도우미'});
  const assertHeadingVisible = async heading => {
   const result = await heading.evaluate(el => {
    const d=el.closest('dialog');
    const bottom=Math.max(...Array.from(d.querySelectorAll('[data-setup-sticky]'),x=>x.getBoundingClientRect().bottom));
    const rect=el.getBoundingClientRect();
    return {focused:el===document.activeElement,visible:rect.top>=bottom && rect.bottom<=d.getBoundingClientRect().bottom};
   });
   assert.deepEqual(result,{focused:true,visible:true},'새 단계 제목은 고정 헤더 아래에 보이고 초점을 받음');
  };
  await dialog.waitFor();
  const help = dialog.locator('details').filter({has:page.locator('summary').filter({hasText:'Gemini 키 만드는 방법'})}).first();
  assert.notEqual(await help.getAttribute('open'),null,'처음 설정 설명은 기본으로 펼침');
  assert.equal(await dialog.getByRole('progressbar').count(),1);
  assert.equal(await dialog.evaluate(el=>el.scrollWidth>el.clientWidth),false);
  await help.getByText('도움말 1 / 4',{exact:true}).waitFor();
  await page.waitForFunction(()=>{const image=document.querySelector('dialog[open] [data-setup-help] img');return image?.complete&&image.naturalWidth>0;});
  assert.equal(await help.locator('img').evaluate(el=>el.complete && el.naturalWidth>0),true);
  assert.equal(await help.getByRole('button',{name:'다음',exact:true}).count(),0);
  for(let i=0;i<3;i++) {
   await help.getByRole('button',{name:'다음 설명 보기',exact:true}).click();
   await assertHeadingVisible(help.getByRole('heading'));
  }
  await help.getByRole('button',{name:'입력칸으로 이동',exact:true}).click();
  assert.equal(await dialog.getByLabel('Gemini API 키 (AI 연결 키)').evaluate(el=>el===document.activeElement),true);
  await help.locator('summary').first().click();
  await mkdir('../artifacts/setup-dialog', {recursive:true});
  await page.screenshot({path:'../artifacts/setup-dialog/compact-google-850.png'});
  await dialog.getByLabel('Gemini API 키 (AI 연결 키)').fill('synthetic-key-only');
  await page.keyboard.press('Escape');
  await dialog.getByText('아직 저장하지 않은 입력이 있습니다.',{exact:false}).waitFor();
  await dialog.getByRole('button',{name:'입력 유지하고 닫기'}).click();
  await dialog.waitFor({state:'hidden'});
  assert.equal(await page.locator('dialog[open]').count(),0);
  await page.getByRole('link',{name:'새 소식 탐색 준비',exact:true}).click();
  assert.equal(await dialog.getByLabel('Gemini API 키 (AI 연결 키)').inputValue(),'synthetic-key-only');
  await dialog.getByRole('button',{name:'저장하고 연결 확인',exact:true}).click();
  await dialog.getByRole('button',{name:'저장 중…',exact:true}).waitFor();
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('dialog[open]').count(),1);
  await page.evaluate(()=>globalThis.__fixtureFinishSave());
  await dialog.getByRole('heading',{name:'수집 대상',exact:true}).waitFor();
  await dialog.getByRole('button',{name:'닫기',exact:true}).click();
  await page.getByRole('link',{name:'정책 최신화 준비',exact:true}).click();
  await dialog.getByLabel('Notion 연결 토큰 (Installation access token)').waitFor();
  await dialog.getByRole('heading',{name:'Notion 가입·로그인',exact:true}).waitFor();
  const notionHelp=dialog.locator('details').filter({has:page.locator('summary').filter({hasText:'Notion 연결 토큰 만드는 방법'})}).first();
  await notionHelp.getByRole('link',{name:'Notion 가입·로그인 열기',exact:false}).waitFor();
  assert.equal(await dialog.getByRole('link',{name:'정책 최신화 화면으로 이동',exact:false}).count(),0,'연결 미완료 시 완료 이동을 표시하지 않음');
  await notionHelp.getByRole('button',{name:'다음 설명 보기',exact:true}).click();
  await notionHelp.getByRole('heading',{name:'내부 연결 만들기',exact:true}).waitFor();
  await notionHelp.getByRole('button',{name:'다음 설명 보기',exact:true}).click();
  await notionHelp.getByRole('heading',{name:'이름과 작업 공간 선택',exact:true}).waitFor();
  await assertHeadingVisible(notionHelp.getByRole('heading'));
  await notionHelp.locator('img').waitFor();
  await mkdir('../artifacts/setup-dialog', {recursive:true});
  await page.screenshot({path:'../artifacts/setup-dialog/notion-workspace-850.png'});
  await page.evaluate(()=>document.documentElement.classList.add('dark'));
  assert.equal(await dialog.evaluate(el=>getComputedStyle(el).backgroundColor), 'rgb(31, 41, 55)');
  await page.screenshot({path:'../artifacts/setup-dialog/notion-workspace-dark-850.png'});
  await page.evaluate(()=>document.documentElement.classList.remove('dark'));
  await notionHelp.getByRole('button',{name:'다음 설명 보기',exact:true}).click();
  await notionHelp.getByRole('heading',{name:'권한 확인 후 토큰 복사',exact:true}).waitFor();
  assert.equal(await dialog.evaluate(el=>el.scrollWidth>el.clientWidth),false);
  await page.keyboard.press('Tab');
  assert.equal(await dialog.evaluate(el=>el.contains(document.activeElement)),true);
  await mkdir('../artifacts/setup-dialog', {recursive:true});
  await page.screenshot({path:'../artifacts/setup-dialog/notion-850.png'});
  await dialog.getByRole('button',{name:'닫기',exact:true}).click();
  await page.locator('aside').getByText('모두 연결',{exact:true}).click();
  await page.locator('aside').getByText('예전 Notion 설정 주소',{exact:true}).click();
  await page.getByRole('link',{name:'정책 최신화 보관함 연결·변경',exact:true}).click();
  await dialog.locator('#setup-section-policy input').first().waitFor();
  await dialog.getByRole('button',{name:'닫기',exact:true}).click();
  await page.locator('aside').getByText('예전 기본 설정 주소',{exact:true}).click();
  await page.getByRole('link',{name:'Gemini 연결 확인·변경',exact:true}).click();
  await dialog.getByLabel('새 Gemini API 키 (변경할 때만 입력) (AI 연결 키)').waitFor();
  assert.equal(await dialog.getByRole('button',{name:'새 키 저장하고 연결 확인',exact:true}).isDisabled(),true);
  const beforeVerify=await page.evaluate(()=>globalThis.__fixtureReadConfig());
  await dialog.getByRole('button',{name:'기존 키 연결 확인',exact:true}).click();
  await dialog.getByRole('heading',{name:'수집 대상',exact:true}).waitFor();
  assert.deepEqual(await page.evaluate(()=>globalThis.__fixtureReadConfig()),beforeVerify);
  assert.deepEqual(errors,[]);
 } finally {await browser.close();}
});
