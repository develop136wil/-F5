import {test,before,after} from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE||'playwright');
const origin=process.env.UI_TEST_ORIGIN||'http://127.0.0.1:1467';
let browser;
before(async()=>{browser=await chromium.launch({channel:'msedge',headless:true});});
after(async()=>{await browser?.close();});
async function open(t){
    const page=await browser.newPage({viewport:{width:1100,height:1000}}),errors=[],blocked=[];
    page.on('pageerror',error=>errors.push(error.message));
    await page.route('**/*',route=>{const url=new URL(route.request().url());
        if(url.origin===origin&&!url.pathname.startsWith('/api/'))return route.continue();
        blocked.push(url.origin+url.pathname);return route.abort();});
    await page.goto(origin+'/tests/ui/blank-start-audit.html');
    t.after(async()=>{assert.deepEqual(await page.evaluate(()=>window.blankAudit.calls.unexpected),[]);assert.deepEqual(errors,[]);assert.deepEqual(blocked,[]);await page.close();});
    return page;
}
test('blank audit: 조건 저장은 사이트를 생성하지 않고 실제 Sites 화면 등록 후 키 없이 원문 수집 가능',async t=>{
    const page=await open(t);
    await page.getByRole('button',{name:'새 소식 찾기',exact:true}).click();
    for(let step=0;step<3;step++)await page.getByRole('button',{name:'다음',exact:true}).click();
    await page.getByRole('button',{name:'최종 저장',exact:true}).click();
    await page.getByText('연결된 수집 사이트가 없습니다.',{exact:true}).waitFor();
    assert.equal(await page.getByRole('button',{name:'새 소식 찾기',exact:true}).isDisabled(),true);
    assert.equal(await page.evaluate(()=>window.blankAudit.state.sites.length),0);
    await page.getByRole('link',{name:'수집 사이트 등록·관리',exact:true}).click();
    await page.getByLabel('공지사항·새 소식 게시판 주소',{exact:true}).fill('https://example.org/notices/list');
    await page.getByRole('button',{name:'주소 등록',exact:true}).click();
    await page.waitForFunction(()=>window.blankAudit.calls.siteAdds.length===1);
    await page.getByRole('link',{name:'새 소식 시험',exact:true}).click();
    await page.getByText(/AI 분석 준비:/).waitFor();
    await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(x=>x.textContent.trim()==='새 소식 찾기'&&!x.disabled));
    await page.getByRole('button',{name:'새 소식 찾기',exact:true}).click();
    await page.getByRole('button',{name:'확인하고 수집 시작',exact:true}).click();
    await page.getByRole('button',{name:'이 작업 중지',exact:true}).waitFor();
    assert.deepEqual(await page.evaluate(()=>window.blankAudit.calls.starts),[{id:'default-news',revision:2}]);
    assert.equal(await page.evaluate(()=>window.blankAudit.state.ai),false);
});
test('blank audit: 정책표 0개 안내→빈 선택지 초안 오류 보존·재분석→등록→첫 최신화',async t=>{
    const page=await open(t);await page.getByRole('link',{name:'정책 시험',exact:true}).click();
    assert.equal(await page.getByRole('link',{name:'정책 최신화 준비하기',exact:true}).getAttribute('href'),'/settings?tab=guide&step=policy');
    assert.equal(await page.getByRole('button',{name:'정책 정보 최신인지 확인하기',exact:true}).isDisabled(),true);
    await page.evaluate(async()=>{window.blankAudit.state.ai=true;await window.blankAudit.connectPolicy();});
    await page.getByRole('button',{name:'첫 정책 초안 만들기',exact:true}).click();
    await page.getByLabel('정책 안내 페이지 주소',{exact:true}).fill('https://example.org/policy/first');
    await page.evaluate(()=>{window.blankAudit.state.previewFailure=true;});
    await page.getByRole('button',{name:'정책 초안 만들기',exact:true}).click();
    await page.getByText('원문 확인 필요: 원문에서 정책 내용을 확인하지 못했습니다.',{exact:true}).waitFor();
    await page.getByRole('status').filter({hasText:'사업명·출처 주소(관련 홈페이지 1)·확인한 내용을 직접 입력'}).waitFor();
    assert.equal(await page.getByRole('group',{name:'정책 초안 검토',exact:true}).count(),0);
    assert.equal(await page.getByLabel('정책 안내 페이지 주소',{exact:true}).inputValue(),'https://example.org/policy/first');
    assert.equal(await page.getByRole('button',{name:'정책 초안 만들기',exact:true}).isEnabled(),true);
    await page.evaluate(()=>{window.blankAudit.state.previewFailure=false;});
    await page.getByRole('button',{name:'정책 초안 만들기',exact:true}).click();
    await page.getByRole('group',{name:'정책 초안 검토',exact:true}).waitFor();
    await page.getByText(/원문 일부를 확인하지 못했습니다: 본문 길이 제한/).waitFor();
    assert.equal(await page.getByText('이 보관함에 등록된 선택지가 없습니다.',{exact:true}).count(),3);
    const confirm=page.getByRole('button',{name:'확인하고 Notion에 추가',exact:true});
    assert.equal(await confirm.isDisabled(),true);
    await page.getByLabel('시작 월령',{exact:true}).fill('120');
    await page.getByLabel('종료 월령',{exact:true}).fill('12');
    for(const checkbox of await page.getByRole('group',{name:'등록 전 원문 대조 확인',exact:true}).getByRole('checkbox').all())await checkbox.check();
    assert.equal(await confirm.isDisabled(),true);
    await page.getByRole('status').filter({hasText:'시작 월령은 종료 월령보다 클 수 없습니다.'}).waitFor();
    assert.equal(await page.evaluate(()=>window.blankAudit.calls.creates.length),0);
    await page.getByLabel('종료 월령',{exact:true}).fill('120');
    for(const checkbox of await page.getByRole('group',{name:'등록 전 원문 대조 확인',exact:true}).getByRole('checkbox').all())await checkbox.check();
    await confirm.click();await page.getByRole('status',{name:'정책 추가 후 다음 단계',exact:true}).waitFor();
    await page.getByRole('button',{name:'정책 최신화로 이동',exact:true}).click();
    await page.waitForFunction(()=>!document.querySelector('[aria-label="첫 정책 시작 안내"]'));
    page.on('dialog',dialog=>dialog.accept());
    await page.getByRole('button',{name:'정책 정보 최신인지 확인하기',exact:true}).click();
    await page.waitForFunction(()=>window.blankAudit.calls.checks.length===1);
    assert.deepEqual(await page.evaluate(()=>window.blankAudit.calls.checks),[['blank']]);
    assert.equal(await page.evaluate(()=>window.blankAudit.calls.previews.length),2);
    assert.equal(await page.evaluate(()=>window.blankAudit.calls.creates.length),1);
});
test('Notion에서 직접 입력한 첫 정책을 동기화하면 로컬 개수와 첫 시작 안내도 갱신한다',async t=>{
    const page=await open(t);await page.getByRole('link',{name:'정책 시험',exact:true}).click();
    await page.evaluate(async()=>{window.blankAudit.state.ai=true;await window.blankAudit.connectPolicy();});
    await page.getByRole('note',{name:'첫 정책 시작 안내'}).waitFor();
    page.on('dialog',dialog=>dialog.accept());
    await page.getByRole('button',{name:'정책 정보 최신인지 확인하기',exact:true}).click();
    await page.waitForFunction(()=>window.blankAudit.calls.checks.length===1);
    await page.evaluate(()=>{window.blankAudit.state.localCount=1;window.blankAudit.state.policyStatus={running:false,state:'completed',phase:'done',message:'모의 첫 비교 완료',total:1,checked:1,initial_compared:1,changed:0};});
    await page.getByText('모의 첫 비교 완료',{exact:true}).waitFor();
    await page.getByRole('note',{name:'첫 정책 시작 안내'}).waitFor({state:'hidden'});
    assert.match(await page.getByRole('button',{name:'빈 시험 정책표',exact:true}).getAttribute('title'),/로컬 1건/);
    assert.equal(await page.evaluate(()=>window.blankAudit.state.localCount),1);
});
