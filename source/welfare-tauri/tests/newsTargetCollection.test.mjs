test('새 조건은 이전 대기를 보존한 채 실행하고 현재 대기·다른 버전 실행 중 작업은 막는다',()=>{
    const oldWaiting={workflow_id:'old',revision:1,state:'waiting'};
    const hasBlocking=(items,revision)=>items.some(item=>blocksNewWorkflow(item,revision));
    assert.equal(hasBlocking([oldWaiting],2),false);
    assert.equal(hasBlocking([oldWaiting],1),true);
    assert.equal(hasBlocking([oldWaiting,{revision:2,state:'waiting'}],2),true);
    assert.equal(hasBlocking([oldWaiting,{revision:1,state:'running'}],2),true);
    assert.equal(hasBlocking([oldWaiting,{state:'waiting'}],2),true);
    assert.deepEqual(oldWaiting,{workflow_id:'old',revision:1,state:'waiting'});
});
