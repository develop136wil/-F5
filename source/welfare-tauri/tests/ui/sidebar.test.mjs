import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {mkdir} from 'node:fs/promises';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE||'playwright');
const origin=process.env.UI_TEST_ORIGIN||'http://127.0.0.1:1420';
test('접힌 메뉴는 이름·진행 상태·중지·펼침 상태 저장을 유지한다',async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try{
 const page=await browser.newPage({viewport:{width:850,height:700}});
 await page.route('**/*',r=>new URL(r.request().url()).origin===origin&&!new URL(r.request().url()).pathname.startsWith('/api/')?r.continue():r.abort());
 await page.goto(`${origin}/tests/ui/sidebar.html`);
 await page.getByText('42%',{exact:true}).waitFor();
 const expandedButton=page.getByRole('button',{name:'메뉴 접기',exact:true});
 const expandedBox=await expandedButton.boundingBox();
 const iconCenter=async locator=>{const box=await locator.boundingBox();return box.x+box.width/2;};
 const toggleIcon=page.locator('[aria-controls="sidebar-links"] [data-menu-toggle]');
 const navIcons=page.locator('#sidebar-links > a > span:first-child svg');
 const expandedCenter=await iconCenter(toggleIcon);
 for(const icon of await navIcons.all()) assert.ok(Math.abs(await iconCenter(icon)-expandedCenter)<1,'메뉴 버튼과 항목 아이콘의 세로 열');
 assert.equal(await expandedButton.locator(':scope > span:last-child').evaluate(el=>getComputedStyle(el).opacity),'0','설명은 상시 표시하지 않음');
 assert.equal(await toggleIcon.getAttribute('data-menu-toggle'),'open');
 const lines=toggleIcon.locator('span');
 assert.equal(await lines.nth(1).evaluate(el=>getComputedStyle(el).opacity),'0','펼침 상태는 X');
 assert.match(await lines.first().evaluate(el=>getComputedStyle(el).transform),/^matrix\(/);
 assert.equal(await lines.first().evaluate(el=>getComputedStyle(el).transitionDuration),'0.2s');
 assert.equal(expandedBox.width,44);assert.equal(expandedBox.height,44);
 assert.equal(await page.locator('#mobile-navigation h1').count(),0);
 await expandedButton.click();
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('[aria-controls="sidebar-links"] [data-menu-toggle] > span:nth-child(2)')).opacity==='1');
 assert.equal(await toggleIcon.getAttribute('data-menu-toggle'),'closed');
 assert.equal(await lines.first().evaluate(el=>getComputedStyle(el).transform),'none','접힘 상태는 햄버거');
 await page.emulateMedia({reducedMotion:'reduce'});
 assert.ok(await lines.first().evaluate(el=>parseFloat(getComputedStyle(el).transitionDuration))<=0.001,'동작 줄이기에서는 전환이 즉시 완료됨');
 await page.emulateMedia({reducedMotion:'no-preference'});
 const collapsedBox=await page.getByRole('button',{name:'메뉴 펼치기',exact:true}).boundingBox();
 assert.equal(collapsedBox.x,expandedBox.x);
 assert.equal(collapsedBox.y,expandedBox.y);
 assert.equal(await iconCenter(toggleIcon),expandedCenter,'접어도 아이콘의 가로 위치 유지');
 for(const icon of await navIcons.all()) assert.ok(Math.abs(await iconCenter(icon)-expandedCenter)<1);
 assert.equal(await page.getByRole('button',{name:'메뉴 펼치기',exact:true}).getByText('메뉴',{exact:true}).count(),0);
 const progress=page.getByRole('button',{name:'작업 진행 중 · 진행 상황',exact:true});
 await progress.click();
 await page.getByText('42%',{exact:true}).waitFor();
 await page.getByRole('button',{name:'중지',exact:true}).click();
 assert.equal(await page.evaluate(()=>window.stops),1);
 await page.keyboard.press('Escape');
 assert.equal(await progress.getAttribute('aria-expanded'),'false');
 assert.equal(await page.getByRole('link',{name:'새 소식',exact:true}).getAttribute('title'),'새 소식');
 const newsLink=page.getByRole('link',{name:'새 소식',exact:true});
 await newsLink.focus();
 assert.equal(await newsLink.locator('span[aria-hidden=true]').evaluate(el=>getComputedStyle(el).opacity),'1');
 await page.evaluate(()=>window.setNewsTasks([{workflow_id:'test-workflow',state:'waiting'}]));
 const attention=page.getByRole('button',{name:'확인 필요 · 진행 상황',exact:true});
 await attention.waitFor({timeout:15000});
 await attention.click();
 await page.getByText('새 소식 · 잠시 멈춤',{exact:true}).waitFor();
 const panel=await page.locator('#sidebar-status').boundingBox();
 assert.ok(panel.x+panel.width<=850 && panel.y>=0);
 await attention.click();
 await mkdir('../artifacts/sidebar',{recursive:true});
 await page.screenshot({path:'../artifacts/sidebar/collapsed.png'});
 await page.reload();
 await page.getByRole('button',{name:'메뉴 펼치기',exact:true}).click();
 await page.waitForFunction(()=>getComputedStyle(document.querySelector('[aria-controls="sidebar-links"] [data-menu-toggle] > span:nth-child(2)')).opacity==='0');
 assert.equal(await toggleIcon.getAttribute('data-menu-toggle'),'open','다시 펼치면 X로 전환');
 assert.equal(await page.evaluate(()=>localStorage.getItem('sidebar-collapsed')),'false');
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 // Reload resets fixture memory, so seed the task again before mobile navigation.
 await page.evaluate(()=>window.setNewsTasks([{workflow_id:'test-workflow',state:'waiting'}]));
 await page.getByText('새 소식 · 잠시 멈춤',{exact:true}).waitFor({timeout:15000});
 assert.equal(await page.getByRole('link',{name:'새 소식에서 진행 확인',exact:true}).count(),0);
 await page.setViewportSize({width:582,height:700});
 await page.getByRole('button',{name:'메뉴 열기',exact:true}).click();
 await page.getByRole('link',{name:'설정',exact:true}).waitFor();
 await page.getByRole('link',{name:'새 소식',exact:true}).click();
 assert.equal(await page.locator('#mobile-navigation').isVisible(),false,'새 소식 메뉴 이동 후 모바일 메뉴를 닫음');
 await page.getByRole('button',{name:'메뉴 열기',exact:true}).click();
 await page.getByRole('button',{name:'메뉴 닫기',exact:true}).last().click();
 assert.equal(await page.locator('#mobile-navigation').isVisible(),false);
 }finally{await browser.close();}
});
