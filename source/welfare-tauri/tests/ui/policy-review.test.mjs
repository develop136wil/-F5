            const firstSummary = page.locator('#policy-review-1 button[aria-controls="policy-detail-1"]');
            await firstSummary.waitFor();
            assert.equal(await page.getByText('중요 변경',{exact:true}).count(),0);
            await page.getByRole('button',{name:'주요·보강',exact:true}).waitFor();
            assert.equal(await page.getByRole('heading',{name:'점검 시 Notion 내용',exact:true}).count(), 0);
            await page.screenshot({path:`../artifacts/policy-review-20260907/summary-${width}.png`});
            await firstSummary.click();
            assert.ok(await page.locator('#policy-detail-1 h3').count() > 0, '속성은 제목으로 구분');
            assert.equal(await page.getByRole('checkbox').count(),0,'기본 화면에는 검토 종료용 선택을 숨김');
            assert.equal(await page.getByRole('button',{name:'반영 없이 목록 정리',exact:true}).count(),0);
            assert.ok(await page.getByRole('heading',{name:'점검 시 Notion 내용',exact:true}).count() > 0);
            assert.ok(await page.getByRole('heading',{name:'변경 제안 · 아직 반영하지 않음',exact:true}).count() > 0);
            await page.getByRole('button',{name:'반영할 내용 선택',exact:true}).first().click();
            const bar = page.getByRole('region',{name:'선택한 정책 작업'});
            await bar.waitFor();
            await firstSummary.click();
            assert.equal(await bar.getByRole('button',{name:'선택한 내용 Notion에 반영 (1)',exact:true}).isEnabled(), true, '접어도 선택 유지');
            await firstSummary.click();
            const box = await bar.boundingBox();
            assert.ok(box.y >= 0 && box.y + box.height <= 650, '첫 선택부터 화면 아래 작업바가 보여야 함');
            await page.locator('main').evaluate(el=>{el.scrollTop=el.scrollHeight/2;});
            const button = bar.getByRole('button',{name:'선택한 내용 Notion에 반영 (1)',exact:true});
            const bounds = await button.boundingBox();
            assert.ok(bounds.y>=0 && bounds.y+bounds.height<=650,'스크롤 후에도 실행 버튼이 보여야 함');
            await page.screenshot({path:`../artifacts/policy-review-20260907/selection-${width}.png`});
            await button.click();
            await page.getByText('0건 적용 · 1건 실패',{exact:true}).waitFor();
            await page.getByText('반영하지 못한 내용 확인 (1)',{exact:true}).click();
            await page.getByText('시험 정책 1 · 분류: 시험 연결 실패',{exact:false}).waitFor();
            await page.getByRole('button', {name:'카드 보기',exact:true}).click();
            await page.waitForFunction(()=>document.activeElement?.id==='policy-review-1');
            assert.ok((await page.locator('#policy-review-1').boundingBox()).y >= 0);
            assert.equal(await page.evaluate(()=>window.policyCalls.length),1);
            await page.getByRole('button',{name:'반영 결과 닫기'}).click();
            await page.getByRole('button',{name:'반영할 내용 선택',exact:true}).first().click();
            await page.getByRole('button',{name:'보강',exact:true}).click();
            assert.equal(await bar.count(),0,'선택이 없으면 하단 중복 작업바 숨김');
            assert.equal(await page.getByRole('button',{name:'선택한 내용 Notion에 반영 (0)',exact:true}).isDisabled(),true,'상단 진입점 유지');
            assert.equal(await page.locator('main').evaluate(el=>el.scrollWidth>el.clientWidth),false);
            assert.deepEqual(errors,[]);
            await page.goto('http://127.0.0.1:1420/tests/ui/policy-review.html?mode=manual');
            const manualCard = page.locator('#policy-review-1');
            await manualCard.locator('button[aria-controls="policy-detail-1"]').click();
            await manualCard.getByRole('button', {name:'바로 적용',exact:true}).waitFor();
            await manualCard.getByRole('button', {name:'반영할 내용 선택',exact:true}).click();
            assert.equal(await page.evaluate(()=>window.individualCalls.length + window.policyCalls.length),0,'임시 선택은 쓰기 없음');
            await page.evaluate(()=>{let count=0;window.confirm=()=>++count===1;});
            await bar.getByRole('button',{name:'선택한 내용 Notion에 반영 (1)',exact:true}).click();
            await page.getByText('0건 적용 · 1건 보류 — 개별 확인 필요',{exact:true}).waitFor();
            assert.equal(await page.evaluate(()=>window.individualCalls.length + window.policyCalls.length),0,'원문 확인 취소는 쓰기 없음');
            await page.goto('http://127.0.0.1:1420/tests/ui/policy-review.html?mode=manual');
            await page.locator('button[aria-controls="policy-detail-1"]').click();
            await page.getByRole('button',{name:'반영할 내용 선택',exact:true}).first().click();
            await page.evaluate(()=>{window.confirm=()=>true;});
            await bar.getByRole('button',{name:'선택한 내용 Notion에 반영 (1)',exact:true}).click();
            await page.getByText('1건 적용',{exact:true}).waitFor();
            assert.equal(await page.evaluate(()=>window.individualCalls.length),1);
            assert.equal(await page.evaluate(()=>window.policyCalls.length),0,'검토 항목은 일반 일괄 API를 우회시키지 않고 개별 적용 경로 사용');
