import React from 'react';
import {createRoot} from 'react-dom/client';
import {MemoryRouter} from 'react-router-dom';
import {QueryClient,QueryClientProvider} from '@tanstack/react-query';
import {welfareApi} from '../../src/api/welfare';
import '../../src/index.css';
for(const key of Object.keys(welfareApi)) if(typeof welfareApi[key]==='function') welfareApi[key]=async()=>({});
welfareApi.getStatus=async()=>({is_running:true,progress:42,message:'시험 수집 중'});
welfareApi.getPolicyTaskStatuses=async()=>['정책 최신화','Notion 불러오기','정책 비교','스타일 제안 생성','변경 제안 다시 확인','출처 변경 확인'].map(label=>({label,running:false}));
window.stops=0;
welfareApi.getNewsProfiles=async()=>({items:[{profile_id:'test-profile',name:'시험 대상'}]});
welfareApi.getNewsWorkflows=async()=>({items:window.newsTasks||[]});
window.newsTasks=[];
welfareApi.stopScrape=async()=>{window.stops++;return {};};
const {ScrapeProvider}=await import('../../src/context/ScrapeContext');
const {default:Layout}=await import('../../src/components/layout/Layout');
const client=new QueryClient();
window.setNewsTasks=async tasks=>{window.newsTasks=tasks;await client.invalidateQueries({queryKey:['global-news-task-status']});};
createRoot(document.getElementById('root')).render(<MemoryRouter><QueryClientProvider client={client}><ScrapeProvider><Layout><h2>시험 본문</h2></Layout></ScrapeProvider></QueryClientProvider></MemoryRouter>);
