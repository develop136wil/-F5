import {test} from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const {chromium}=createRequire(import.meta.url)(process.env.PLAYWRIGHT_MODULE || 'playwright');
test('조건 생성 → 목록 → 수정 → 재열기에서 세부 대상과 나이 보존',async()=>{
 const browser=await chromium.launch({channel:'msedge',headless:true});
 try{
  const page=await browser.newPage();const errors=[];
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('**/*',r=>new URL(r.request().url()).origin==='http://127.0.0.1:1420'?r.continue():r.abort());
  await page.goto('http://127.0.0.1:1420/tests/ui/condition-flow.html');
  const button=name=>page.getByRole('button',{name,exact:true});
  await button('새 조건 만들기').click();await button('취소').click();
  assert.equal(await page.evaluate(()=>window.fixture.creates),0);
  await button('새 조건 만들기').click();
  await page.getByLabel('시·도',{exact:true}).selectOption('서울특별시');
  await page.getByLabel('시·군·구 (선택)',{exact:true}).fill('도봉구');
  await button('다음').click();await button('아동').click();await button('다문화').click();
  await button('다음').click();await page.getByRole('radiogroup',{name:'시작 나이 제한 선택'}).getByRole('radio',{name:'나이 지정',exact:true}).check();
  await page.getByLabel('시작 나이 만 나이',{exact:true}).fill('6');
  await page.getByLabel('시작 나이 추가 개월',{exact:true}).fill('3');
  await button('다음').click();
  assert.equal(await page.evaluate(()=>window.fixture.creates),0);
  await button('최종 저장').click();await button('조건 수정').click();
  await page.getByLabel('시·도',{exact:true}).waitFor();
  assert.equal(await page.getByLabel('시·군·구 (선택)',{exact:true}).inputValue(),'도봉구');
  await button('다음').click();
  assert.equal(await page.getByRole('button',{name:'✓ 다문화',exact:true}).getAttribute('aria-pressed'),'true');
  await button('다음').click();
  assert.equal(await page.getByLabel('시작 나이 추가 개월',{exact:true}).inputValue(),'3');
  await page.getByLabel('시작 나이 추가 개월',{exact:true}).fill('4');
  await button('다음').click();await button('최종 저장').click();
  await page.locator('summary').filter({hasText:'더 보기'}).click();await button('추가 설정').click();
  const region=page.getByLabel('대상 지역 (제한 없으면 전국)',{exact:true});
  await region.waitFor();assert.equal(await region.inputValue(),'서울특별시 도봉구');
  assert.equal(await page.getByLabel('시작 나이 만 나이',{exact:true}).inputValue(),'6');
  assert.equal(await page.getByLabel('시작 나이 추가 개월',{exact:true}).inputValue(),'4');
  await page.getByLabel('조건 이름',{exact:true}).fill('도봉구 아동 소식');
  await button('수집 조건 저장').click();await page.locator('summary').filter({hasText:'더 보기'}).click();await button('추가 설정').click();
  await region.waitFor();
  assert.equal(await page.getByLabel('조건 이름',{exact:true}).inputValue(),'도봉구 아동 소식');
  const state=await page.evaluate(()=>window.fixture);
  assert.equal(state.creates,1);assert.equal(state.updates,2);
  assert.deepEqual(state.items[0].characteristics,['다문화']);
  assert.deepEqual(state.items[0].life_cycles,['아동']);
  assert.deepEqual(state.items[0].site_ids,['1']);
  assert.equal(state.items[0].min_age_months,76);assert.equal(state.items[0].max_age_months,null);
  assert.deepEqual(errors,[]);
 }finally{await browser.close();}
});
